/*
 * arch/aarch64/font8x8.c -- kappara 8x8 ASCII glyphs
 * ==================================================
 *
 * Original glyph designs for printable ASCII (0x20..0x7E).  Each
 * character is an 8-byte array, one byte per row of pixels.  Within
 * a row byte, bit 0 = leftmost pixel, bit 4 = rightmost active
 * pixel; we draw inside a 5-wide, 7-tall sub-cell of the 8x8 grid
 * which leaves 3 columns and 1 row of inter-glyph padding.
 *
 * Indexed by ASCII code so framebuffer_putc does:
 *     const uint8_t *g = font8x8[(unsigned char)c];
 *
 * Anything outside the printable range is the all-zero "space"
 * glyph so unmapped characters render as blanks.
 *
 * Storage: 128 * 8 = 1 KB in .rodata.
 */

